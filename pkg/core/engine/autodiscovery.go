// LoadAutoDiscovery runs autodiscovery under the provided context so that
// crawler spans can be linked to the calling prepare span.
//
//nolint:funlen
func (e *Engine) LoadAutoDiscovery(ctx context.Context, defaultEnabled bool) error {
	// Default Autodiscovery pipeline
	if defaultEnabled {
		logrus.Debugf("Default Autodiscovery crawlers enabled")
		var defaultPipeline pipeline.Pipeline
		defaultConfig := &config.Config{
			Spec: config.Spec{
				Name:          "Local AutoDiscovery",
				AutoDiscovery: autodiscovery.GetDefaultCrawlerSpecs(),
			},
		}
		defaultConfig.SetManifestID("autodiscovery/default")

		err := defaultPipeline.Init(defaultConfig, pipeline.Options{})
		if err != nil {
			logrus.Errorln(err)
		} else {
			e.Pipelines = append(e.Pipelines, &defaultPipeline)
			e.configurations = append(e.configurations, defaultConfig)
		}
	}

	PrintTitle("Auto Discovery")

	for id, p := range e.Pipelines {
		if p.Config.Spec.AutoDiscovery.Crawlers == nil {
			continue
		}

		PrintTitle(p.Name)

		var actionConfig *action.Config
		var autodiscoveryScm scm.Scm
		var autodiscoveryAction action.Action
		var found bool

		// Crawlers walk the same tree the manifest resolves its own relative paths from.
		workDir := p.Config.BaseDir()
		if workDir == "" {
			var err error
			workDir, err = os.Getwd()
			if err != nil {
				return fmt.Errorf("failed getting current working directory due to %v", err)
			}
		}

		// Retrieve scm spec if it exists
		if len(p.Config.Spec.AutoDiscovery.ScmId) > 0 {
			autodiscoveryScm, found = p.SCMs[p.Config.Spec.AutoDiscovery.ScmId]

			if found {
				if err := autodiscoveryScm.Handler.Checkout(); err != nil {
					logrus.Errorf("git checkout: %s", err)
				}
				workDir = autodiscoveryScm.Handler.GetDirectory()
			}
		}

		/** Check for deprecated items **/
		if p.Config.Spec.AutoDiscovery.PullrequestId != "" {
			if p.Config.Spec.AutoDiscovery.ActionId != "" {
				return fmt.Errorf("the `autodiscovery.pullrequestid` and `autodiscovery.actionid` keywords are mutually exclusive. Please use only `autodiscovery.actionid` as `autodiscovery.pullrequestid` is deprecated")
			}

			logrus.Warningf("The `autodiscovery.pullrequestid` keyword is deprecated in favor of `autodiscovery.actionid`, please update this manifest. Updatecli will continue the execution while trying to translate `autodiscovery.pullrequestid` to `autodiscovery.actionid`.")

			p.Config.Spec.AutoDiscovery.ActionId = p.Config.Spec.AutoDiscovery.PullrequestId
			p.Config.Spec.AutoDiscovery.PullrequestId = ""
		}

		// Retrieve action spec if it exists
		if len(p.Config.Spec.AutoDiscovery.ActionId) > 0 {
			autodiscoveryAction, found = p.Actions[p.Config.Spec.AutoDiscovery.ActionId]

			if found {
				actionConfig = &autodiscoveryAction.Config
			}
		}

		c, err := autodiscovery.New(
			p.Config.Spec.AutoDiscovery, workDir)
		if err != nil {
			e.Pipelines[id].Report.Result = result.FAILURE
			logrus.Errorln(err)
			return err
		}

		errs := []error{}
		crawlerResults, err := c.Run(ctx)
		if err != nil {
			e.Pipelines[id].Report.Result = result.FAILURE
			logrus.Errorln(err)
			return err
		}

		totalManifests := 0
		for _, cr := range crawlerResults {
			totalManifests += len(cr.Manifests)
		}
		if totalManifests == 0 {
			logrus.Infof("nothing detected")
		}

		generatedManifestIndex := 0
		for _, crawlerResult := range crawlerResults {
			for i := range crawlerResult.Manifests {
				manifest := config.Spec{}

				// We expected manifest generated by the autodiscovery to use the yaml syntax
				err = yaml.Unmarshal(crawlerResult.Manifests[i], &manifest)
				if err != nil {
					return err
				}

				// Propagate user defined labels to autodiscovery generated pipelines
				if len(p.Config.Spec.Labels) > 0 {
					for k, v := range p.Config.Spec.Labels {
						if manifest.Labels == nil {
							manifest.Labels = make(map[string]string)
						}

						if _, ok := manifest.Labels[k]; ok {
							logrus.Warningf("Label %q defined in autodiscovery pipeline %q is overwriting an existing label defined in the discovered pipeline %q",
								k,
								p.Config.Spec.Name,
								manifest.Name)
						}
						manifest.Labels[k] = v
					}
				}

				switch p.Config.Spec.AutoDiscovery.GroupBy {
				/*
					By default if "group by" is not set then we fallback to all
					which means that we generate a single pipeline for all discovered manifests
					The goal is to have a "safe" default behavior and to avoid to accidentally generate
					dozens pullrequests for a single updatecli run
				*/
				case autodiscovery.GROUPBYALL, "":
					manifest.PipelineID = p.Config.Spec.PipelineID
				case autodiscovery.GROUPBYINDIVIDUAL:
					hash := sha256.New()
					/*
						We need to generate an uniq ID per individual pipeline
						but we shouldn't use the manifest of a pipeline
						because it may change over pipeline execution
						such as different source version filter

						Starting the id with the autodiscovery pipelineid looks enough
						to avoid collision
					*/
					_, err := io.WriteString(hash, p.Config.Spec.PipelineID+"/"+manifest.Name)
					if err != nil {
						logrus.Errorln(err)
					}
					manifest.PipelineID = fmt.Sprintf("%x", hash.Sum(nil))
				case autodiscovery.GROUPBYRESOURCE:
					/*
						"resource" groups discovered manifests by the identity of the single
						resource (dependency) they track, e.g. the same Helm chart, Maven
						artifact, npm package or container image, however many times or files
						it was discovered in. Every manifest tracking the same resource lands
						on the same pipelineid/branch, so they end up on the same pull request.

						A manifest discovered with more than one source has no single resource
						identity to group by, so it falls back to the uniq-per-manifest
						behavior of "individual".
					*/
					groupKey, ok := manifestResourceIdentity(manifest)
					if !ok {
						groupKey = manifest.Name
						logrus.Debugf("autodiscovery groupby %q: could not determine a single resource identity for manifest %q, falling back to grouping it individually",
							autodiscovery.GROUPBYRESOURCE, manifest.Name)
					}

					hash := sha256.New()
					_, err := io.WriteString(hash, p.Config.Spec.PipelineID+"/"+groupKey)
					if err != nil {
						logrus.Errorln(err)
					}
					manifest.PipelineID = fmt.Sprintf("%x", hash.Sum(nil))
				}

				if manifest.ID == "" {
					manifest.ID = p.Config.Spec.ID
				}

				manifest.DependsOn = mergeManifestDependencies(manifest.DependsOn, p.Config.Spec.DependsOn)

				// Only add the scm if it is not already defined
				if len(manifest.SCMs) == 0 {
					manifest.SCMs = make(map[string]scm.Config)
				}

				autodiscoveryGeneratedSCMs := maps.Keys(manifest.SCMs)
				for scmId := range p.SCMs {
					// Copy the raw scm configuration, with its directory pinned against this
					// manifest's base directory: the generated manifest resolves its own
					// paths from workDir, which must not apply to these scms a second time.
					manifest.SCMs[scmId] = pipeline.PinScmDirectory(p.Config.Spec.SCMs[scmId], p.Config.BaseDir())
				}

				if actionConfig != nil {
					// Only initialize the action if it is not already defined
					if len(manifest.Actions) == 0 {
						manifest.Actions = make(map[string]action.Config)
					}
					if (p.Config.Spec.AutoDiscovery.GroupBy == autodiscovery.GROUPBYALL ||
						p.Config.Spec.AutoDiscovery.GroupBy == "") &&
						actionConfig.Title == "" {
						/*
							Normally the config spec name should never be empty as it is a required field according the jsonschema spec
						*/
						actionConfig.Title = p.Config.Spec.Name
						if actionConfig.Title == "" {
							/*
								If Autodiscovery option "groupby" is set to "all" and if associated action title are set to "empty"
								then we want to be sure that the action title is not empty by using a generic title.
								Otherwise each pipeline generated by the autodiscovery will have a different title which will constantly update the pullrequest title.
							*/
							defaultActionTitle := "deps: bumping various version"
							logrus.Warningf("action title %q used by autodiscovery is empty, fallback to generic:\n\t=> %s",
								p.Config.Spec.AutoDiscovery.ActionId,
								defaultActionTitle)
							actionConfig.Title = defaultActionTitle
						}
					}

					manifestAction := manifest.Actions[p.Config.Spec.AutoDiscovery.ScmId]

					baseAction := *actionConfig

					if name, ok := manifestResourceName(manifest); ok {
						baseAction.Spec = appendActionLabel(baseAction.Spec, p.Config.Spec.AutoDiscovery.ResourceLabelPrefix+name)
					}

					if err := mergo.Merge(&baseAction, manifestAction); err != nil {
						fmt.Println("Error:", err)
					}
					manifest.Actions[p.Config.Spec.AutoDiscovery.ActionId] = baseAction
				}

				if manifest.Version != "" {
					manifest.Version = version.Version
				}

				newConfig := config.Config{
					Spec: manifest,
				}
				// A generated manifest has no file on disk, but the paths its crawler
				// produced are relative to workDir, so that is what it resolves from.
				newConfig.SetBaseDir(workDir)
				manifestFingerprint, err := autodiscoveryManifestFingerprint(newConfig.Spec, p.Config.Spec.PipelineID)
				if err != nil {
					return fmt.Errorf("computing autodiscovery manifest fingerprint for %q: %w", manifest.Name, err)
				}

				newConfig.SetManifestID(fmt.Sprintf("%s/autodiscovery/%s/%d/%s",
					p.Config.ManifestID(),
					crawlerResult.Kind,
					generatedManifestIndex,
					manifestFingerprint,
				))
				generatedManifestIndex++

				newPipeline := pipeline.Pipeline{}
				err = newPipeline.Init(&newConfig, e.Options.Pipeline)
				if err == nil {
					newPipeline.CrawlerKind = crawlerResult.Kind
				}

				// We must clone any scm generated by autodiscovery
				if len(autodiscoveryGeneratedSCMs) > 0 {
					hashes := []uint64{}
					wg := sync.WaitGroup{}
					channel := make(chan int, 20)
					defer wg.Wait()

					for _, id := range autodiscoveryGeneratedSCMs {
						s := newPipeline.SCMs[id]
						if s.Handler != nil {
							logrus.Debugf("scm %s generated by autodiscovery must be cloned in %s", id, s.Handler.GetDirectory())
							err = Clone(&s.Handler, channel, &hashes, &wg)
							if err != nil {
								logrus.Debugf("Error while cloning autodiscovery %s - %s", s.Handler.GetDirectory(), err)
							}
						}
					}
				}

				if err == nil {
					e.Pipelines = append(e.Pipelines, &newPipeline)
					e.configurations = append(e.configurations, &newConfig)
				} else {
					e.Pipelines[id].Report.Result = result.FAILURE
					// don't initially fail as init. of the pipeline still fails even with a successful validation
					err := fmt.Errorf("%q - %s", manifest.Name, err)
					errs = append(errs, err)
				}
				if len(errs) > 0 {
					e.Pipelines[id].Report.Result = result.FAILURE

					logrus.Errorf("Error(s) happened while generating Updatecli pipeline manifest")
					for i := range errs {
						logrus.Errorf("%v", errs[i])
					}
				}
			}
		}

		e.Pipelines[id].Report.Result = result.SUCCESS

	}

	return nil
}

// manifestResourceIdentity returns a stable identity for the single resource (dependency) a
// discovered manifest tracks, used to group pipelines with "groupby: resource". It returns
// ok=false when the manifest does not have exactly one source, since there is then no single
// resource identity to group by.
func manifestResourceIdentity(manifest config.Spec) (string, bool) {
	if len(manifest.Sources) != 1 {
		return "", false
	}

	for _, src := range manifest.Sources {
		reportConfig, err := resource.GetReportConfig(src.ResourceConfig)
		if err != nil {
			return "", false
		}

		sanitizedResourceConfig, ok := reportConfig.(resource.ResourceConfig)
		if !ok {
			return "", false
		}

		// Only the resource "kind" and "spec" identify the resource being tracked. The
		// resource's own "name" is a free-form, per-manifest display label (e.g. the helmfile
		// crawler sets it to the release name) and must not affect the identity, or two
		// manifests tracking the exact same resource under a different display label would
		// wrongly be considered distinct resources.
		data, err := json.Marshal(sanitizedResourceConfig.Spec)
		if err != nil {
			return "", false
		}

		return fmt.Sprintf("%s/%x", src.Kind, sha256.Sum256(data)), true
	}

	// unreachable: the len(manifest.Sources) == 1 check above guarantees exactly one iteration
	return "", false
}

// manifestResourceName returns the "name" field of a discovered manifest's single source spec,
// used to build the extra label "autodiscovery.resourcelabelprefix" adds. It returns ok=false
// when the manifest does not have exactly one source, or that source's spec has no non-empty
// string "name" field.
func manifestResourceName(manifest config.Spec) (string, bool) {
	if len(manifest.Sources) != 1 {
		return "", false
	}

	for _, src := range manifest.Sources {
		specMap, ok := src.Spec.(map[string]interface{})
		if !ok {
			return "", false
		}

		name, ok := specMap["name"].(string)
		if !ok || name == "" {
			return "", false
		}

		return name, true
	}

	// unreachable: the len(manifest.Sources) == 1 check above guarantees exactly one iteration
	return "", false
}

// appendActionLabel returns a copy of an action's spec with label appended to its "labels"
// list. It never mutates spec in place, since the autodiscovery action config is shared and
// reused as a template for every manifest the autodiscovery pipeline generates.
func appendActionLabel(spec interface{}, label string) interface{} {
	specMap, ok := spec.(map[string]interface{})
	if !ok {
		return spec
	}

	newSpec := make(map[string]interface{}, len(specMap))
	for k, v := range specMap {
		newSpec[k] = v
	}

	existingLabels, _ := specMap["labels"].([]interface{})
	newLabels := make([]interface{}, 0, len(existingLabels)+1)
	newLabels = append(newLabels, existingLabels...)
	newLabels = append(newLabels, label)
	newSpec["labels"] = newLabels

	return newSpec
}

func autodiscoveryManifestFingerprint(manifest config.Spec, pipelineID string) (string, error) {
	sanitized := manifest

	if len(manifest.Sources) > 0 {
		sanitized.Sources = make(map[string]source.Config, len(manifest.Sources))
		for id, cfg := range manifest.Sources {
			reportConfig, err := resource.GetReportConfig(cfg.ResourceConfig)
			if err != nil {
				return "", fmt.Errorf("sanitizing source %q: %w", id, err)
			}

			sanitizedResourceConfig, ok := reportConfig.(resource.ResourceConfig)
			if !ok {
				return "", fmt.Errorf("unexpected report config type %T", reportConfig)
			}

			cfg.ResourceConfig = sanitizedResourceConfig
			sanitized.Sources[id] = cfg
		}
	}

	if len(manifest.Conditions) > 0 {
		sanitized.Conditions = make(map[string]condition.Config, len(manifest.Conditions))
		for id, cfg := range manifest.Conditions {
			reportConfig, err := resource.GetReportConfig(cfg.ResourceConfig)
			if err != nil {
				return "", fmt.Errorf("sanitizing condition %q: %w", id, err)
			}

			sanitizedResourceConfig, ok := reportConfig.(resource.ResourceConfig)
			if !ok {
				return "", fmt.Errorf("unexpected report config type %T", reportConfig)
			}

			cfg.ResourceConfig = sanitizedResourceConfig
			sanitized.Conditions[id] = cfg
		}
	}

	if len(manifest.Targets) > 0 {
		sanitized.Targets = make(map[string]target.Config, len(manifest.Targets))
		for id, cfg := range manifest.Targets {
			reportConfig, err := resource.GetReportConfig(cfg.ResourceConfig)
			if err != nil {
				return "", fmt.Errorf("sanitizing target %q: %w", id, err)
			}

			sanitizedResourceConfig, ok := reportConfig.(resource.ResourceConfig)
			if !ok {
				return "", fmt.Errorf("unexpected report config type %T", reportConfig)
			}

			cfg.ResourceConfig = sanitizedResourceConfig
			sanitized.Targets[id] = cfg
		}
	}

	if len(manifest.SCMs) > 0 {
		sanitized.SCMs = make(map[string]scm.Config, len(manifest.SCMs))
		for id, cfg := range manifest.SCMs {
			if cfg.Disabled || cfg.Spec == nil {
				cfg.Spec = nil
			} else if generatedSCM, err := scm.New(&cfg, pipelineID); err == nil && generatedSCM.Handler != nil {
				cfg.Spec = generatedSCM.Handler.Summary()
			} else {
				cfg.Spec = cfg.Kind
			}

			sanitized.SCMs[id] = cfg
		}
	}

	data, err := json.Marshal(sanitized)
	if err != nil {
		return "", err
	}

	return fmt.Sprintf("%x", sha256.Sum256(data)), nil
}
